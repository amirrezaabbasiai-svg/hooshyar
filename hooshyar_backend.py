def admin_classes(user=Depends(admin)):
    """Boss dashboard: per-class mastery comparison (six classes: grade × major)."""
    with db() as con:
        studs = con.execute("SELECT id,name,profile FROM users WHERE role='student'").fetchall()
        out = {}
        for s in studs:
            try: k = json.loads(s["profile"] or "{}").get("class", "—")
            except Exception: k = "—"
            ms = mastery(con, s["id"])
            avg = round(sum(v["m"] for v in ms.values()) / len(ms), 1) if ms else None
            c = out.setdefault(k, {"class": k, "students": [], "avg": None, "per_lesson": {}})
            c["students"].append({"id": s["id"], "name": s["name"], "avg": avg})
            for lid, v in ms.items():
                c["per_lesson"].setdefault(lid, []).append(v["m"])
        for c in out.values():
            vals = [s["avg"] for s in c["students"] if s["avg"] is not None]
            c["avg"] = round(sum(vals) / len(vals), 1) if vals else None
            c["per_lesson"] = {lid: round(sum(v) / len(v)) for lid, v in c["per_lesson"].items()}
    return list(out.values())

