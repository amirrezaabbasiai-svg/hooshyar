# ---------------------------------------------------------------- auth
def token(uid: str, role: str) -> str:
    return base64.urlsafe_b64encode(f"{role}:{uid}".encode()).decode()

def auth(authorization: Optional[str] = Header(None)):
    if not authorization: raise HTTPException(401, "token missing")
    try:
        role, uid = base64.urlsafe_b64decode(authorization.replace("Bearer ", "")).decode().split(":")
    except Exception: raise HTTPException(401, "bad token")
    with db() as con:
        u = con.execute("SELECT * FROM users WHERE id=?", (uid,)).fetchone()
    if not u or u["role"] != role: raise HTTPException(403, "unknown user")
    return {"id": uid, "role": role, "name": u["name"]}

def teacher(user=Depends(auth)):
    if user["role"] != "teacher": raise HTTPException(403, "teachers only")
    return user

def admin(user=Depends(auth)):
    if user["role"] != "admin": raise HTTPException(403, "admins only")
    return user

def staff(user=Depends(auth)):
    if user["role"] not in ("teacher", "admin"): raise HTTPException(403, "staff only")
    return user

# ---------------------------------------------------------------- core logic
def grade_mcq(qs: list, ans: list) -> dict:
    c = w = b = 0; per_l: dict = {}; tash = []
    for i, q in enumerate(qs):
        if q.get("type") == "tashrihi":
            tash.append({"i": i, "q": q, "grade": LLM.grade_tashrihi(q, ans[i] or "")}); continue
        x = per_l.setdefault(q["l"], {"c": 0, "w": 0, "b": 0, "t": 0}); x["t"] += 1
        r = ans[i]
        if r is None: b += 1; x["b"] += 1
        elif r == q["a"]: c += 1; x["c"] += 1
        else: w += 1; x["w"] += 1
    n = len(qs) - len(tash)
    if n:
        pct = KONKUR(c, w, n)
    elif tash:   # آزمون کاملاً تشریحی: headline grade = mean of rubric scores
        pct = round(sum((x["grade"].get("final") if x["grade"].get("final") is not None else x["grade"]["score"]) for x in tash) / len(tash), 1)
    else:
        pct = 0.0
    return {"c": c, "w": w, "b": b, "pct": pct, "perL": per_l, "tashrihi": tash, "n": n}

def lesson_pct(x: dict) -> float: return KONKUR(x["c"], x["w"], x["t"])

def mastery(con, uid: str) -> dict:
    out = {}
    for row in con.execute("SELECT lesson,p,t FROM stats WHERE user_id=? ORDER BY t", (uid,)):
        out.setdefault(row["lesson"], []).append({"p": row["p"], "t": row["t"]})
    res = {}
    for lid, tries in out.items():
        last, avg = tries[-1]["p"], sum(x["p"] for x in tries) / len(tries)
        age = (time.time() - tries[-1]["t"]) / 86400
        m = max(0, min(100, round(0.55 * last + 0.45 * avg)))
        res[lid] = {"m": m, "n": len(tries), "age_days": round(age)}
    return res

def build_plan(con, uid: str, rng: random.Random) -> dict:
    ms = mastery(con, uid)
    rows = []
    for sid, sub in SUBJECTS.items():
        for lid, lname in sub["lessons"].items():
            m = ms.get(lid, {}).get("m", 30); age = ms.get(lid, {}).get("age_days", 21)
            rows.append({"lid": lid, "name": lname, "coef": sub["coef"], "m": m,
                         "pr": (100 - m) * sub["coef"] * (1 + 0.5 * min(age, 21) / 21)})
    rows.sort(key=lambda r: -r["pr"])
    days = ["شنبه", "یکشنبه", "دوشنبه", "سه‌شنبه", "چهارشنبه", "پنجشنبه", "جمعه"]
    plan = {d: [] for d in days}
    for i, r in enumerate(rows[:9]):
        plan[days[i % 6]].append({"topic": r["name"], "mins": 35 + (i % 3) * 10,
                                  "stars": 3 if r["pr"] > 140 else 2 if r["pr"] > 80 else 1})
    weak = [r["name"] for r in rows if r["m"] < 50][:3]
    plan["پنجشنبه"].append({"topic": "آزمون کوتاه ۱۵ تایی از مباحث ضعیف: " + ("، ".join(weak) or "مباحث اخیر"), "mins": 40, "stars": 3})
    plan["جمعه"].append({"topic": "استراحت + مرور اشتباهات", "mins": 20, "stars": 1})
    return plan

