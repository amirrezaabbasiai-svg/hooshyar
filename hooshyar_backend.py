@app.post("/attempts")
def attempt(body: AttemptIn, user=Depends(auth)):
    with db() as con:
        r = con.execute("SELECT qs FROM exams WHERE id=?", (body.exam_id,)).fetchone()
        if not r: raise HTTPException(404, "not found")
        qs = json.loads(r["qs"])
        if len(body.answers) != len(qs): raise HTTPException(400, "answers length mismatch")
        res = grade_mcq(qs, body.answers)
        aid = f"a{int(time.time()*1000)}{user['id']}"
        con.execute("INSERT INTO attempts VALUES(?,?,?,?,?,?)",
                    (aid, body.exam_id, user["id"], json.dumps(body.answers, ensure_ascii=False), json.dumps(res, ensure_ascii=False), time.time()))
        for lid, x in res["perL"].items():
            con.execute("INSERT INTO stats VALUES(?,?,?,?)", (user["id"], lid, lesson_pct(x), time.time()))
        for x in res["tashrihi"]:
            con.execute("INSERT INTO stats VALUES(?,?,?,?)", (user["id"], x["q"]["l"], x["grade"]["score"], time.time()))
        con.commit()
    return res | {"attempt_id": aid}

